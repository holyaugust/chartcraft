/**
 * 职场公文模板正文（完整范文级，占位符用 ×××× / ×月×日 标注可替换处）
 */

function workplaceDoc(
  docType: string,
  title: string,
  recipient: string,
  body: string,
  closing?: string,
  signer?: string,
): string {
  const closingLine = closing ? `\n\n${closing}` : ''
  const signBlock = signer ?? '××有限公司综合管理部\n2025年×月×日'
  return `【文种：${docType}】

【标题：${title}】

${recipient}

${body}${closingLine}

${signBlock}`
}

function workplaceReport(
  docType: string,
  title: string,
  body: string,
  footer?: string,
): string {
  const footerBlock =
    footer ??
    `报送：公司领导班子
编制单位：××部
联系人：×××  联系电话：×××
日期：2025年×月×日`
  return `【文种：${docType}】

【标题：${title}】

${body}

${footerBlock}`
}

